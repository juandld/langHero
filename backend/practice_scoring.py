"""Jev-backed scorer for a single learner utterance in /practice.

Wraps lib/jev_client.call() with the 4 calibrated dims (grammatical,
natural, register, meaning) plus one native-speaker alternative, so
routes/practice.py (and any future async batch grader) has a single
call surface.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from lib import jev_client

DIMENSIONS = ("grammatical", "natural", "register", "meaning")

# Deterministic stand-in for Jev scores, used when MOCK_JEV=1 so E2E/CI runs
# don't burn Jev tokens or wait on the live API. Values are mid-band (not 0
# or 1) so they exercise the yellow/green UI paths and match the frontend's
# /^0?\.\d+$/ score-attribute assertion.
MOCK_SCORES = {"grammatical": 0.82, "natural": 0.75, "register": 0.9, "meaning": 0.65}

# langHero's backend runs as a long-lived --reload'd uvicorn process (systemd
# langhero-backend.service), so a MOCK_JEV env var set only for a test-runner
# shell never reaches the already-running server. The sentinel file lets
# `tests/global-setup.ts` flip mocking on for that live process without a
# restart; checked fresh on every call, not cached at import time.
MOCK_FLAG_PATH = Path(__file__).resolve().parent / ".mock_jev_flag"


def mock_enabled() -> bool:
    """True when MOCK_JEV is active — also used by routes/practice.py to skip
    the (much slower) LLM tutor-turn call, since that call, not Jev, is what
    actually blows the E2E test's 5s score-render budget."""
    return os.environ.get("MOCK_JEV") == "1" or MOCK_FLAG_PATH.exists()


def _questions(target_language: str, scenario: str, user_intent: str) -> dict:
    # Jev (typesafe.ai/v1/systemone) only supports calibrated question types
    # (noul/choice/score) — no freeform text generation. Confirmed live:
    # {"type": "string"} returns HTTP 400 "Invalid request." The
    # native-speaker "alternative" rewrite is generated by the LLM tutor
    # call in routes/practice.py instead, not by Jev.
    return {
        "grammatical": {
            "type": "noul",
            "instructions": f"Is this {target_language} sentence grammatically correct?",
        },
        "natural": {
            "type": "noul",
            "instructions": (
                f"Would a native {target_language} speaker say this naturally, "
                "or does it sound like a textbook?"
            ),
        },
        "register": {
            "type": "noul",
            "instructions": (
                f"Given the scenario ({scenario}), is this the appropriate register?"
            ),
        },
        "meaning": {
            "type": "noul",
            "instructions": (
                f"Does this preserve the learner's intended meaning ({user_intent})?"
            ),
        },
    }


def _clamp01(value: Any) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return 0.0
    return max(0.0, min(1.0, v))


def score_utterance(
    *,
    target_language: str,
    scenario: str,
    history: list[dict] | None,
    user_intent: str,
    utterance: str,
) -> dict:
    """Score a learner's utterance on 4 calibrated dims via Jev.

    Returns {"grammatical": float, "natural": float, "register": float,
    "meaning": float, "alternative": str}.
    """
    if mock_enabled():
        return {**MOCK_SCORES, "alternative": ""}

    state = {
        "sentence": utterance,
        "target_language": target_language,
        "scenario": scenario,
        "learner_intent": user_intent,
        "conversation_so_far": history or [],
    }

    answers = jev_client.call(
        state=state,
        questions=_questions(target_language, scenario, user_intent),
        api_key=os.environ.get("JEV_API_TOKEN") or None,
    )

    result: dict[str, Any] = {}
    for dim in DIMENSIONS:
        result[dim] = _clamp01((answers.get(dim) or {}).get("noul"))
    # Jev has no freeform-text question type (see _questions comment above),
    # so the native-speaker alternative comes from the LLM tutor call in
    # routes/practice.py instead — leave this empty here.
    result["alternative"] = ""
    return result
